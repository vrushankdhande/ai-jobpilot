"""DOCX export (python-docx): single-column, ATS-friendly resume, cover letter and screening answers."""
import io
import re

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_TAB_ALIGNMENT
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Inches, Pt, RGBColor

from ai.schemas.document_schema import CoverLetterContent, ResumeContent, ScreeningContent, parse_content
from engines.generation.render import format_period, month_name

FONT = "Calibri"
BLUE = RGBColor(0x05, 0x63, 0xC1)
GREY = RGBColor(0x59, 0x59, 0x59)
PAGES = {"A4": (8.27, 11.69), "LETTER": (8.5, 11.0)}
_CTRL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f￾￿]")


def clean(text) -> str:
    return _CTRL.sub("", str(text)) if text is not None else ""


def _font(run, size=10.5, bold=False, italic=False, color=None):
    run.font.name = FONT
    run._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    run.font.size, run.font.bold, run.font.italic = Pt(size), bold, italic
    if color is not None:
        run.font.color.rgb = color


def _para(doc, text="", size=10.5, bold=False, italic=False, color=None, align=None, after=3, before=0, keep_next=False):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_after, pf.space_before, pf.keep_with_next, pf.widow_control = Pt(after), Pt(before), keep_next, True
    if align is not None:
        p.alignment = align
    if text:
        _font(p.add_run(clean(text)), size, bold, italic, color)
    return p


def add_hyperlink(paragraph, url: str, text: str, size=10.5):
    """A real, clickable external hyperlink."""
    r_id = paragraph.part.relate_to(url, "http://schemas.openxmlformats.org/officeDocument/2006/relationships/hyperlink", is_external=True)
    link = OxmlElement("w:hyperlink")
    link.set(qn("r:id"), r_id)
    run = OxmlElement("w:r")
    rpr = OxmlElement("w:rPr")
    for tag, attrs in (("w:rFonts", {"w:ascii": FONT, "w:hAnsi": FONT}), ("w:color", {"w:val": "0563C1"}), ("w:u", {"w:val": "single"}),
                       ("w:sz", {"w:val": str(int(size * 2))})):
        el = OxmlElement(tag)
        for k, v in attrs.items():
            el.set(qn(k), v)
        rpr.append(el)
    run.append(rpr)
    t = OxmlElement("w:t")
    t.text = clean(text)
    t.set(qn("xml:space"), "preserve")
    run.append(t)
    link.append(run)
    paragraph._p.append(link)


def _heading(doc, text):
    p = _para(doc, text.upper(), size=11, bold=True, color=RGBColor(0x1F, 0x2D, 0x3D), before=8, after=3, keep_next=True)
    ppr = p._p.get_or_add_pPr()
    border = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    for k, v in (("w:val", "single"), ("w:sz", "6"), ("w:space", "1"), ("w:color", "7F8C8D")):
        bottom.set(qn(k), v)
    border.append(bottom)
    ppr.append(border)
    return p


def _bullet(doc, text, size=10.5):
    p = doc.add_paragraph(style="List Bullet")
    pf = p.paragraph_format
    pf.space_after, pf.space_before, pf.left_indent, pf.first_line_indent = Pt(1.5), Pt(0), Inches(0.22), Inches(-0.18)
    _font(p.add_run(clean(text)), size)
    return p


def _entry(doc, left_bold, left_rest, right, width):
    p = _para(doc, after=1, before=4, keep_next=True)
    p.paragraph_format.tab_stops.add_tab_stop(Inches(width), WD_TAB_ALIGNMENT.RIGHT)
    _font(p.add_run(clean(left_bold)), 10.5, bold=True)
    if left_rest:
        _font(p.add_run(clean(" | " + left_rest)), 10.5, italic=True)
    if right:
        _font(p.add_run("\t" + clean(right)), 10, color=GREY)
    return p


def _setup(title: str, author: str | None, page: str, approved: bool):
    doc = Document()
    sec = doc.sections[0]
    sec.page_width, sec.page_height = (Inches(x) for x in PAGES.get(page.upper(), PAGES["A4"]))
    sec.left_margin = sec.right_margin = Inches(0.75)
    sec.top_margin, sec.bottom_margin = Inches(0.65), Inches(0.7)
    normal = doc.styles["Normal"]
    normal.font.name, normal.font.size = FONT, Pt(10.5)
    normal.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    doc.core_properties.title, doc.core_properties.author, doc.core_properties.subject = clean(title), clean(author or ""), "Generated by AI JobPilot"
    if not approved:
        fp = sec.footer.paragraphs[0]
        fp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        _font(fp.add_run("DRAFT - not approved for submission"), 8, italic=True, color=GREY)
    width = (PAGES.get(page.upper(), PAGES["A4"])[0]) - 1.5
    return doc, width


def _contact_line(doc, h: dict, align=WD_ALIGN_PARAGRAPH.CENTER):
    p = _para(doc, align=align, after=4)
    first = True
    for label, key in (("", "email"), ("", "phone"), ("", "location"), ("LinkedIn", "linkedin_url"), ("GitHub", "github_url"), ("Portfolio", "portfolio_url")):
        val = h.get(key)
        if not val:
            continue
        if not first:
            _font(p.add_run("  |  "), 10, color=GREY)
        first = False
        if key == "email":
            add_hyperlink(p, f"mailto:{val}", val, 10)
        elif key.endswith("_url"):
            add_hyperlink(p, val, label, 10)
        else:
            _font(p.add_run(clean(val)), 10)


def build_resume_docx(c: ResumeContent, approved: bool, page: str = "A4", title: str | None = None) -> bytes:
    h = c.header.model_dump()
    doc, width = _setup(title or f"Resume - {h.get('full_name') or ''}", h.get("full_name"), page, approved)
    _para(doc, h.get("full_name") or "", size=20, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER, after=1)
    if h.get("headline"):
        _para(doc, h["headline"], size=11, color=GREY, align=WD_ALIGN_PARAGRAPH.CENTER, after=2)
    _contact_line(doc, h)
    if c.summary:
        _heading(doc, "Summary")
        _para(doc, c.summary, after=2)
    if c.skills:
        _heading(doc, "Skills")
        for g in c.skills:
            p = _para(doc, after=1)
            _font(p.add_run(clean(g.label + ": ")), 10.5, bold=True)
            _font(p.add_run(clean(", ".join(g.items))), 10.5)
    if c.experience:
        _heading(doc, "Experience")
        for e in c.experience:
            _entry(doc, e.company_name or "", e.job_title or "", format_period(e.start_date, e.end_date, e.is_current), width)
            if e.location:
                _para(doc, e.location, size=9.5, italic=True, color=GREY, after=1, keep_next=True)
            for b in e.bullets:
                _bullet(doc, b.text)
    if c.projects:
        _heading(doc, "Projects")
        for pr in c.projects:
            p = _para(doc, after=1, before=4, keep_next=True)
            _font(p.add_run(clean(pr.project_name or "")), 10.5, bold=True)
            if pr.technologies:
                _font(p.add_run(clean("  |  " + ", ".join(pr.technologies))), 10, italic=True, color=GREY)
            if pr.project_url:
                _font(p.add_run("  |  "), 10, color=GREY)
                add_hyperlink(p, pr.project_url, "Link", 10)
            for b in pr.bullets:
                _bullet(doc, b.text)
    if c.education:
        _heading(doc, "Education")
        for e in c.education:
            yrs = " - ".join(str(y) for y in (e.start_year, e.graduation_year) if y)
            title = ", ".join(x for x in [e.degree, e.specialization] if x)
            _entry(doc, title, e.institution or "", yrs, width)
            if e.grade:
                _para(doc, e.grade, size=9.5, color=GREY, after=1)
    if c.certifications:
        _heading(doc, "Certifications")
        for x in c.certifications:
            _entry(doc, x.certification_name or "", x.issuing_organization or "", month_name(x.issue_date) or "", width)
    if c.achievements:
        _heading(doc, "Achievements")
        for a in c.achievements:
            _bullet(doc, a.text)
    out = io.BytesIO()
    doc.save(out)
    return out.getvalue()


def build_cover_letter_docx(c: CoverLetterContent, header: dict, approved: bool, page: str = "A4") -> bytes:
    doc, _ = _setup(f"Cover letter - {c.job_title or ''}", header.get("full_name"), page, approved)
    _para(doc, header.get("full_name") or c.signature or "", size=16, bold=True, after=1)
    _contact_line(doc, header, align=WD_ALIGN_PARAGRAPH.LEFT)
    _para(doc, "", after=6)
    _para(doc, c.salutation, after=8)
    for p in c.paragraphs:
        _para(doc, p.text, after=8).paragraph_format.line_spacing = 1.1
    _para(doc, c.closing, after=18, before=4)
    _para(doc, c.signature or "", bold=True)
    out = io.BytesIO()
    doc.save(out)
    return out.getvalue()


def build_screening_docx(c: ScreeningContent, header: dict, title: str, approved: bool, page: str = "A4") -> bytes:
    doc, _ = _setup(title, header.get("full_name"), page, approved)
    _para(doc, title, size=15, bold=True, after=2)
    _para(doc, header.get("full_name") or "", size=10.5, color=GREY, after=8)
    for a in c.answers:
        _para(doc, a.question, bold=True, after=2, before=6, keep_next=True)
        _para(doc, a.answer, after=4).paragraph_format.line_spacing = 1.1
    out = io.BytesIO()
    doc.save(out)
    return out.getvalue()


def export_docx(doc_type: str, content: dict, header: dict, title: str, approved: bool, page: str = "A4") -> bytes:
    parsed = parse_content(doc_type, content)
    if doc_type == "resume":
        return build_resume_docx(parsed, approved, page, title or None)
    if doc_type == "cover_letter":
        return build_cover_letter_docx(parsed, header, approved, page)
    return build_screening_docx(parsed, header, title, approved, page)
